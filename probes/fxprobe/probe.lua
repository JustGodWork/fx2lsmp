local function try(name, fn)
  local ok, value = pcall(fn)
  print(("PROBE lua %s ok=%s value=%s"):format(name, tostring(ok), tostring(value)))
end
try("Vector3.basic", function()
  local v = Vector3(1, 2, 3)
  local mt = getmetatable(v)
  return table.concat({ type(v), tostring(v), tostring((v + v).x), tostring((v * 2.0).z), tostring(#v), tostring(v == Vector3(1, 2, 3)), type(mt), tostring(mt and mt.__name) }, " | ")
end)
try("Vector3.mt.keys", function() local t = {} for k in pairs(getmetatable(Vector3(0, 0, 0)) or {}) do t[#t + 1] = tostring(k) end table.sort(t) return table.concat(t, ",") end)
try("Vector3.fields", function() local v = Vector3(1, 2, 3) return tostring(v.x) .. "," .. tostring(v[1]) .. "," .. tostring(v.length) end)
try("Vector3.setfield", function() local v = Vector3(1, 2, 3) v.x = 5 return v.x end)
try("Vector3.table.arg", function() return tostring(lsmp.getClosestPlayer({ x = 0.0, y = 0.0, z = 0.0 })) end)
