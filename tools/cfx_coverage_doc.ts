import { RUNTIMES, runtimesOf, type CfxData, type CfxEntry, type Runtime } from "./fx2lsmp/cfxCoverage.ts";

const VERBS: ReadonlySet<string> = new Set([
  "Get", "Set", "Is", "Has", "Does", "Add", "Remove", "Clear", "Create", "Delete", "Reset", "Register", "Unregister",
  "Find", "Start", "End", "Enable", "Disable", "Apply", "Load", "Request", "Send", "Override", "Can", "Perform", "All",
  "Save", "Update", "Select", "Activate", "Call", "Break", "Clone", "Commit", "Destroy", "Duplicate", "Ensure", "Enter",
  "Leave", "Flag", "Force", "Format", "Prepare", "Print", "Remap", "Scan", "Schedule", "Shutdown", "Temp", "Verify",
]);

const FAMILY_RULES: readonly [RegExp, string][] = [
  [/Kvp/, "Kvp"],
  [/Convar/, "Convar"],
  [/StateBag/, "StateBag"],
  [/Nui|Dui/, "Nui"],
  [/Mumble/, "Mumble"],
  [/Resource/, "Resource"],
];

/** FiveM category of a name: a keyword rule, else the first word that is not a leading verb. */
export function familyOf(name: string): string {
  for (const [pattern, family] of FAMILY_RULES) if (pattern.test(name)) return family;
  const words = name.match(/[A-Z][a-z0-9]*/g) ?? [name];
  return words.find((w) => !VERBS.has(w)) ?? words[0] ?? name;
}

const GUESS = " (guess)";

/** Ordered heuristics, first match wins; every result is a guess made from the name and the apiset alone. */
const CLASS_RULES: readonly [(name: string, entry: CfxEntry) => boolean, string][] = [
  [(n) => /Mumble|VoiceChannel/.test(n), "lsmp-api candidate: lsmp.voice"],
  [(n) => /Kvp/.test(n), "lsmp-api candidate: lsmp.storage"],
  [(n) => /RuntimeTexture|ReplaceTexture|Dui/.test(n), "lsmp-api candidate: lsmp.createTexture"],
  [(n) => /Nui|LoadingScreen/.test(n), "lsmp-api candidate: lsmp.createBrowser"],
  [(n) => /Commerce|Sku|PasswordHash|TempBan|Private|Telemetry/.test(n), "impossible"],
  [(n) => /^(Profiler|Experimental|Onesync|EnableEnhanced|FormatStack|PrintStructured|ScheduleResource)|EditorRuntime|Timecycle|Mapdata|Minimap|Bigmap|Corona|Gizmo|Draw|Idle|RawKey|Raw[A-Z]*Keymap|Override|Cursor/.test(n), "harmless no-op"],
  [(n) => /Convar|Resource|Metadata|Function[A-Z]|HttpRequest/.test(n), "lsmp-api candidate: lsmp.resources and convars"],
  [(n, e) => e.apiset === "server" && /Blip|Entity|Player|Ped|Vehicle|Object|Weapon|Task|Boat|Train|Pickup|Network|Door/.test(n), "lsmp-api candidate: lsmp entity and player APIs"],
  [(_n, e) => e.apiset === "client", "impossible"],
];

export function classOf(name: string, entry: CfxEntry): string {
  for (const [test, label] of CLASS_RULES) if (test(name, entry)) return label + GUESS;
  return "unclassified";
}

function missing(entry: CfxEntry): Runtime[] {
  return runtimesOf(entry.apiset).filter((runtime) => !entry.covered.includes(runtime));
}

function totals(data: CfxData): string[] {
  const entries = Object.values(data.natives);
  const lines = ["| apiset | natives | " + RUNTIMES.join(" | ") + " |", "|:-|-:|" + RUNTIMES.map(() => "-:").join("|") + "|"];
  for (const apiset of ["shared", "client", "server"] as const) {
    const of = entries.filter((e) => e.apiset === apiset);
    const cells = RUNTIMES.map((rt) => (runtimesOf(apiset).includes(rt) ? `${of.filter((e) => e.covered.includes(rt)).length}/${of.length}` : "n/a"));
    lines.push(`| ${apiset} | ${of.length} | ${cells.join(" | ")} |`);
  }
  const cells = RUNTIMES.map((rt) => {
    const applicable = entries.filter((e) => runtimesOf(e.apiset).includes(rt));
    return `${applicable.filter((e) => e.covered.includes(rt)).length}/${applicable.length}`;
  });
  lines.push(`| all | ${entries.length} | ${cells.join(" | ")} |`);
  return lines;
}

function parityGaps(data: CfxData): string[] {
  const out: string[] = [];
  for (const side of ["client", "server"] as const) {
    const lua = `lua.${side}` as const;
    const js = `js.${side}` as const;
    const only = (a: Runtime, b: Runtime): string[] =>
      Object.entries(data.natives).filter(([, e]) => e.covered.includes(a) && !e.covered.includes(b)).map(([n]) => n).sort();
    out.push(`- ${side}, Lua only: ${only(lua, js).join(", ") || "none"}`);
    out.push(`- ${side}, JS only: ${only(js, lua).join(", ") || "none"}`);
  }
  return out;
}

export function renderCoverageDoc(data: CfxData): string {
  const groups = new Map<string, [string, CfxEntry][]>();
  for (const [name, entry] of Object.entries(data.natives)) {
    if (missing(entry).length === 0) continue;
    const family = familyOf(name);
    const list = groups.get(family) ?? [];
    list.push([name, entry]);
    groups.set(family, list);
  }
  const ordered = [...groups.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
  const lines = [
    "# CFX native coverage (generated by `npm run cfx:coverage`, do not edit)",
    "",
    "A name is covered when the real shim defines it as a function after loading in the test harness (the fake LS:MP host is excluded), or, on a client, when the LS:MP catalogue provides it (shim/js/natives_data.json). Data: tools/fx2lsmp/cfx_natives.json.",
    "",
    "## Totals (covered/applicable)",
    "",
    ...totals(data),
    "",
    "## Lua and JS parity gaps",
    "",
    ...parityGaps(data),
    "",
    "## Class heuristics",
    "",
    "The `class` column is a guess from the name and the apiset only, first matching rule wins: Mumble to lsmp.voice, Kvp to lsmp.storage, runtime textures and Dui to lsmp.createTexture, Nui and loading screen to lsmp.createBrowser, commerce, SKU, password hash and ban natives impossible, profiler, editor, timecycle, minimap, draw, raw key and override natives harmless no-op, convar and resource natives to lsmp.resources, server entity, player, ped, vehicle, blip and task natives to the lsmp entity and player APIs, any other client native impossible (the LS:MP client catalogue lacks it). `unclassified` matches no rule. Nothing here was verified against the LS:MP API beyond the existence of the lsmp.* names in docs/raw/sdk.md.",
    "",
    "## Families of uncovered natives",
    "",
    "| family | uncovered |",
    "|:-|-:|",
    ...ordered.map(([family, list]) => `| ${family} | ${list.length} |`),
    "",
    "## Uncovered natives by family",
  ];
  for (const [family, list] of ordered) {
    lines.push("", `### ${family} (${list.length})`, "", "| name | apiset | missing in | class (guess) |", "|:-|:-|:-|:-|");
    for (const [name, entry] of list.sort((a, b) => a[0].localeCompare(b[0]))) {
      lines.push(`| ${name} | ${entry.apiset} | ${missing(entry).join(", ")} | ${classOf(name, entry)} |`);
    }
  }
  return lines.join("\n") + "\n";
}
